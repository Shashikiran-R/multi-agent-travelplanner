"""
Pydantic V2 Schemas for Quality Assurance, Constraint Validation, and Review Feedback.
"""

from typing import List, Literal, Optional
from pydantic import BaseModel, Field


class ViolationItem(BaseModel):
    """
    Specific constraint violation or quality defect identified by the Review Agent.
    """
    rule_name: str = Field(..., description="e.g. budget_limit, opening_hours, transit_feasibility, thermal_safety")
    severity: Literal["critical", "warning", "suggestion"] = Field(
        default="critical",
        description="Critical issues block approval and trigger revision loops; warnings/suggestions are advisory"
    )
    message: str = Field(..., description="Clear explanation of the detected conflict or violation")
    affected_day: Optional[int] = Field(None, ge=1, description="Day number where the issue occurred")
    suggested_action: Optional[str] = Field(None, description="Recommended fix or replacement")


class ReviewFeedback(BaseModel):
    """
    Formal audit report generated by the Review Agent for the current proposed itinerary.
    """
    passed: bool = Field(
        ...,
        description="True if the itinerary satisfies all mandatory constraints (budget, hours, schedule)"
    )
    violations: List[str] = Field(
        default_factory=list,
        description="High-level summary list of violation messages"
    )
    structured_violations: List[ViolationItem] = Field(
        default_factory=list,
        description="Detailed list of specific violation records"
    )
    cost_delta_aed: float = Field(
        default=0.0,
        description="Amount by which budget was exceeded (positive means deficit, 0 or negative means on budget)"
    )
    recommended_swaps: List[str] = Field(
        default_factory=list,
        description="Prioritized actionable replacement directives for the revision node"
    )
    revision_round: int = Field(
        default=0,
        ge=0,
        description="Current iteration count (0 = first draft, 1 = first revision, etc.)"
    )
    audit_notes: Optional[str] = Field(
        default=None,
        description="General feedback or commendations on plan pacing and coherence"
    )
